#Завдання 9: Аналіз матриці
# Спочатку зчитуємо розміри матриці n та k
n = int(input("Введіть кількість рядків n: "))
k = int(input("Введіть кількість стовпчиків k: "))

# Заповнюємо матрицю
# Вводитимемо числа по рядках через split(), бо так зручніше й швидше
matrix = []
print("Введіть елементи матриці (по рядках через пробіл):")
for i in range(n):
    row = [int(x) for x in input(f"Рядок {i + 1}: ").split()]
    matrix.append(row)

# Рахуємо суми для кожного рядка
# Мені підказали, що тут ідеально підходить вбудована sum(), бо кожен рядок — це вже список
row_sums = [sum(row) for row in matrix]

# А от із стовпчиками трохи покрутимося, бо треба рухатися "вертикально"
# Зовнішній цикл робимо по стовпчиках j, а внутрішній — по рядках i
col_sums = []
for j in range(k):
    col_total = 0
    for i in range(n):
        col_total += matrix[i][j]
    col_sums.append(col_total)

# Наприкінці виводимо готові списки з сумами
print("Суми за рядками:", row_sums)
print("Суми за стовпчиками:", col_sums)