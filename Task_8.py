# Завдання 8: Розрізання вектора
arr = [10, 20, 30, 40, 50, 60, 70]
# 1. Перші 3 елементи (від початку до індексу 3, не включно)
print(f"Перші 3 елементи: {arr[:3]}")
# 2. Останні 2 елементи (використання від'ємного індексу)
print(f"Останні 2 елементи: {arr[-2:]}")
# 3. Весь масив у зворотному порядку (з кроком -1)
print(f"Масив у зворотному порядку: {arr[::-1]}")