# 1. Зчитуємо рядок від користувача
# Одразу переводимо в нижній регістр (.lower()), щоб 'А' і 'а' рахувалися як одна літера
text = input("Введіть рядок тексту: ").lower()

# 2. За підказкою створюємо порожній словник
# Тут ключем буде сама літера, а значенням — скільки разів вона зустрілася
char_dict = {}

# 3. Проходимося по кожному символу в тексті
for char in text:
    # Тут мені чат нагадав про .isalpha(), щоб ми рахували тільки літери (без пробілів і розділових знаків)
    if char.isalpha():
        # Щоб не викликати .count() по 10 разів для однієї й тієї ж літери,
        # додаємо її в словник тільки якщо її там ще немає
        if char not in char_dict:
            # Записуємо в словник кількість входжень через метод .count()
            char_dict[char] = text.count(char)

# 4. Шукаємо в словнику літеру з найбільшим значенням
most_frequent = ""
max_value = 0

# Проходимося по парах (літера, кількість) у нашому словнику через .items()
for letter, count in char_dict.items():
    if count > max_value:
        max_value = count
        most_frequent = letter

# 5. Виводимо результат
# За умовою потрібна саме ВЕЛИКА літера, тому перетворюємо її через .upper()
print("Найчастіша літера:", most_frequent.upper())