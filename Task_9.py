# Завдання 9: Аналіз оцінок
# Початковий список оцінок
marks = [8, 11, 7, 10]
# 1. Видаляємо найнижчу оцінку (7) за значенням
marks.remove(7)
# 2. Додаємо нову оцінку 12 у кінець списку
marks.append(12)
# 3. Сортуємо список від найбільшої до найменшої оцінки
marks.sort(reverse=True)
# Виведення результату
print(f"Відсортований список оцінок: {marks}")