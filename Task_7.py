# Завдання 7: Фільтрація чисел
for i in range(1, 51):
    # 1. Спочатку перевіряємо умову для повної зупинки циклу
    if i == 20:
        break
    # 2. Потім перевіряємо умову пропуску (числа, що діляться на 3)
    if i % 3 == 0:
        continue
    # Виводимо числа, які пройшли фільтрацію
    print(i)